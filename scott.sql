-- Oracle Classic SCOTT/TIGER Schema Creation Script (demobld.sql)

-- 1. SCOTT 계정 초기화 및 생성
DROP USER scott CASCADE;

CREATE USER scott IDENTIFIED BY tiger
  DEFAULT TABLESPACE users
  TEMPORARY TABLESPACE temp
  QUOTA UNLIMITED ON users;

GRANT CONNECT, RESOURCE, CREATE SESSION TO scott;
GRANT CREATE TABLE, CREATE VIEW, CREATE SEQUENCE TO scott;

-- 2. SCOTT 테이불 생성 및 데이터 입력
ALTER SESSION SET CURRENT_SCHEMA = scott;

DROP TABLE emp PURGE;
DROP TABLE dept PURGE;
DROP TABLE bonus PURGE;
DROP TABLE salgrade PURGE;

CREATE TABLE dept (
  deptno NUMBER(2) CONSTRAINT pk_dept PRIMARY KEY,
  dname  VARCHAR2(14),
  loc    VARCHAR2(13)
);

CREATE TABLE emp (
  empno    NUMBER(4) CONSTRAINT pk_emp PRIMARY KEY,
  ename    VARCHAR2(10),
  job      VARCHAR2(9),
  mgr      NUMBER(4),
  hiredate DATE,
  sal      NUMBER(7,2),
  comm     NUMBER(7,2),
  deptno   NUMBER(2) CONSTRAINT fk_deptno REFERENCES dept(deptno)
);

CREATE TABLE bonus (
  ename VARCHAR2(10),
  job   VARCHAR2(9),
  sal   NUMBER,
  comm  NUMBER
);

CREATE TABLE salgrade (
  grade NUMBER,
  losal NUMBER,
  hisal NUMBER
);

